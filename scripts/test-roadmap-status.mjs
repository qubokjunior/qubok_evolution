import { readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const readText = (relativePath) => readFileSync(resolve(projectRoot, relativePath), "utf8");
const assert = (condition, message) => { if (!condition) throw new Error(message); };
const packageJson = JSON.parse(readText("package.json"));
const appVersion = readText("src/shared/appVersion.ts");
const readme = readText("README.md");
const roadmap = readText("docs/roadmap.md");
const architectureTracks = readText("docs/architecture_tracks.md");
const integrationM34 = readText("docs/integration_m35.md");
const pixiRenderer = readText("src/render/pixiRenderer.ts");
assert(packageJson.version === "0.1.0-milestone.35", "package.json must expose m35 version.");
assert(appVersion.includes("PROJECT_VERSION = \"0.1.0-milestone.35\""), "appVersion must expose milestone.35.");
assert(appVersion.includes("PROJECT_MILESTONE_LABEL = \"m35\""), "appVersion must expose m35 label.");
assert(readme.includes("docs/roadmap.md"), "README.md must link docs/roadmap.md.");
assert(roadmap.includes("m35 shipped: terrain movement query integration"), "roadmap must mention m35 terrain debug render layer shipment.");
assert(architectureTracks.includes("src/render/pixiRenderer.ts"), "architecture tracks must mention Pixi terrain debug rendering.");
assert(pixiRenderer.includes("renderTerrainLayer"), "movement must sample terrain.");
assert(integrationM34.includes("terrain debug render layer"), "integration_m35 must describe terrain debug render layer.");
assert(packageJson.scripts.test.includes("test:roadmap-status"), "npm run test must include test:roadmap-status.");
console.log("roadmap status tests passed");
