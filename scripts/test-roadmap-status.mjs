import { readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const readText = (relativePath) => readFileSync(resolve(projectRoot, relativePath), "utf8");
const assert = (condition, message) => { if (!condition) throw new Error(message); };
const packageJson = JSON.parse(readText("package.json"));
const appVersion = readText("src/shared/appVersion.ts");
const readme = readText("README.md");
const roadmap = readText("docs/roadmap.md");
const architectureTracks = readText("docs/architecture_tracks.md");
const integrationM37 = readText("docs/integration_m37.md");
const sensors = readText("src/sim/sensors.ts");
const debugOverlay = readText("src/render/debugOverlay.ts");
const perfMetrics = readText("src/shared/perfMetrics.ts");
const pixiRenderer = readText("src/render/pixiRenderer.ts");
assert(packageJson.version === "0.1.0-milestone.37", "package.json must expose m37 version.");
assert(appVersion.includes("PROJECT_VERSION = \"0.1.0-milestone.37\""), "appVersion must expose milestone.37.");
assert(appVersion.includes("PROJECT_MILESTONE = 37"), "appVersion must expose milestone number 37.");
assert(appVersion.includes("PROJECT_MILESTONE_LABEL = \"m37\""), "appVersion must expose m37 label.");
assert(readme.includes("docs/roadmap.md"), "README.md must link docs/roadmap.md.");
assert(roadmap.includes("m35 shipped: terrain movement query integration"), "roadmap must include m35 terrain movement query.");
assert(roadmap.includes("m36 shipped: terrain resource-affinity spawning and respawning"), "roadmap must include m36 terrain resource affinity.");
assert(roadmap.includes("m37 shipped: terrain-aware sensor sampling on controlled cadence"), "roadmap must include m37 terrain sensor sampling.");
assert(architectureTracks.includes("later sensor query integration"), "architecture tracks must mention terrain sensor query integration.");
assert(sensors.includes("terrainTickInterval"), "sensors must expose terrainTickInterval.");
assert(sensors.includes("terrainSensorSampleCount"), "sensors must expose terrain sensor sample stats.");
assert(sensors.includes("sampleTerrainAtPosition"), "sensors must sample terrain.");
assert(debugOverlay.includes("terrain sensor samples"), "debug overlay must expose terrain sensor sample label.");
assert(perfMetrics.includes("terrainSensorSampleCount"), "perf metrics must expose terrainSensorSampleCount.");
assert(pixiRenderer.includes("terrainSensorSampleCount"), "pixi renderer must record terrainSensorSampleCount.");
assert(integrationM37.includes("terrain-aware sensor sampling"), "integration_m37 must describe terrain-aware sensor sampling.");
assert(packageJson.scripts.test.includes("test:roadmap-status"), "npm run test must include test:roadmap-status.");
console.log("roadmap status tests passed");
