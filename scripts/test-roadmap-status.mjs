import { readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const readText = (relativePath) => readFileSync(resolve(projectRoot, relativePath), "utf8");
const assert = (condition, message) => { if (!condition) throw new Error(message); };
const packageJson = JSON.parse(readText("package.json"));
const appVersion = readText("src/shared/appVersion.ts");
const readme = readText("README.md");
const roadmap = readText("docs/roadmap.md");
const architectureTracks = readText("docs/architecture_tracks.md");
const integrationM39 = readText("docs/integration_m39.md");
const field = readText("src/sim/field.ts");
const movement = readText("src/sim/movement.ts");
const debugOverlay = readText("src/render/debugOverlay.ts");
const perfMetrics = readText("src/shared/perfMetrics.ts");
const pixiRenderer = readText("src/render/pixiRenderer.ts");
const demoSimulation = readText("src/sim/demoSimulation.ts");
assert(packageJson.version === "0.1.0-milestone.39", "package.json must expose m39 version.");
assert(appVersion.includes("PROJECT_VERSION = \"0.1.0-milestone.39\""), "appVersion must expose milestone.39.");
assert(appVersion.includes("PROJECT_MILESTONE = 39"), "appVersion must expose milestone number 39.");
assert(appVersion.includes("PROJECT_MILESTONE_LABEL = \"m39\""), "appVersion must expose m39 label.");
assert(readme.includes("docs/roadmap.md"), "README.md must link docs/roadmap.md.");
assert(roadmap.includes("m38 shipped: terrain-aware reproduction placement using offspring habitat acceptance"), "roadmap must include m38 terrain reproduction placement.");
assert(roadmap.includes("m39 shipped: low-resolution environmental flow field sampled by movement"), "roadmap must include m39 field milestone.");
assert(roadmap.includes("m40 environmental field render snapshot and Pixi vector debug layer"), "roadmap must include m40 field render next candidate.");
assert(architectureTracks.includes("renderer must not own authoritative simulation state"), "architecture tracks must preserve sim/render boundary.");
assert(field.includes("FIELD_LAYER_VERSION"), "field must expose FIELD_LAYER_VERSION.");
assert(field.includes("sampleFieldAtPosition"), "field must expose sampleFieldAtPosition.");
assert(movement.includes("field?: EnvironmentalFieldLayer"), "movement must accept field layer.");
assert(movement.includes("fieldMovementSampleCount"), "movement must expose field movement stats.");
assert(demoSimulation.includes("seedDemoField"), "demoSimulation must seed field.");
assert(demoSimulation.includes("fieldForceScale"), "demoSimulation must expose fieldForceScale.");
assert(debugOverlay.includes("field move samples"), "debug overlay must expose field sample label.");
assert(perfMetrics.includes("fieldFlowMagnitudeSum"), "perf metrics must expose fieldFlowMagnitudeSum.");
assert(pixiRenderer.includes("fieldMovementSampleCount"), "pixi renderer must record fieldMovementSampleCount.");
assert(integrationM39.includes("environmental flow field"), "integration_m39 must describe environmental flow field.");
assert(packageJson.scripts.test.includes("test:roadmap-status"), "npm run test must include test:roadmap-status.");
console.log("roadmap status tests passed");
