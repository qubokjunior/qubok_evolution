import { readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const readText = (relativePath) => readFileSync(resolve(projectRoot, relativePath), "utf8");
const assert = (condition, message) => { if (!condition) throw new Error(message); };
const packageJson = JSON.parse(readText("package.json"));
const appVersion = readText("src/shared/appVersion.ts");
const readme = readText("README.md");
const roadmap = readText("docs/roadmap.md");
const architectureTracks = readText("docs/architecture_tracks.md");
const integrationM36 = readText("docs/integration_m36.md");
const spawnValidation = readText("src/sim/spawnValidation.ts");
const debugOverlay = readText("src/render/debugOverlay.ts");
const perfMetrics = readText("src/shared/perfMetrics.ts");
assert(packageJson.version === "0.1.0-milestone.36", "package.json must expose m36 version.");
assert(appVersion.includes("PROJECT_VERSION = \"0.1.0-milestone.36\""), "appVersion must expose milestone.36.");
assert(appVersion.includes("PROJECT_MILESTONE = 36"), "appVersion must expose milestone number 36.");
assert(appVersion.includes("PROJECT_MILESTONE_LABEL = \"m36\""), "appVersion must expose m36 label.");
assert(readme.includes("docs/roadmap.md"), "README.md must link docs/roadmap.md.");
assert(roadmap.includes("m34 shipped: terrain Pixi debug render layer"), "roadmap must include m34 terrain render layer.");
assert(roadmap.includes("m35 shipped: terrain movement query integration"), "roadmap must include m35 terrain movement query.");
assert(roadmap.includes("m36 shipped: terrain resource-affinity spawning and respawning"), "roadmap must include m36 terrain resource affinity.");
assert(architectureTracks.includes("resource-affinity spawn integration"), "architecture tracks must mention terrain resource-affinity spawn integration.");
assert(spawnValidation.includes("terrainResourceSampleCount"), "spawn validation must expose terrain resource sample stats.");
assert(debugOverlay.includes("terrain food samples"), "debug overlay must expose terrain food sample label.");
assert(perfMetrics.includes("terrainResourceSampleCount"), "perf metrics must expose terrainResourceSampleCount.");
assert(integrationM36.includes("terrain resource affinity"), "integration_m36 must describe terrain resource affinity.");
assert(packageJson.scripts.test.includes("test:roadmap-status"), "npm run test must include test:roadmap-status.");
console.log("roadmap status tests passed");
