import { readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const readText = (relativePath) => readFileSync(resolve(projectRoot, relativePath), "utf8");
const assert = (condition, message) => { if (!condition) throw new Error(message); };
const packageJson = JSON.parse(readText("package.json"));
const appVersion = readText("src/shared/appVersion.ts");
const readme = readText("README.md");
const roadmap = readText("docs/roadmap.md");
const architectureTracks = readText("docs/architecture_tracks.md");
const integrationM38 = readText("docs/integration_m38.md");
const reproduction = readText("src/sim/reproduction.ts");
const debugOverlay = readText("src/render/debugOverlay.ts");
const perfMetrics = readText("src/shared/perfMetrics.ts");
const pixiRenderer = readText("src/render/pixiRenderer.ts");
const demoSimulation = readText("src/sim/demoSimulation.ts");
assert(packageJson.version === "0.1.0-milestone.38", "package.json must expose m38 version.");
assert(appVersion.includes("PROJECT_VERSION = \"0.1.0-milestone.38\""), "appVersion must expose milestone.38.");
assert(appVersion.includes("PROJECT_MILESTONE = 38"), "appVersion must expose milestone number 38.");
assert(appVersion.includes("PROJECT_MILESTONE_LABEL = \"m38\""), "appVersion must expose m38 label.");
assert(readme.includes("docs/roadmap.md"), "README.md must link docs/roadmap.md.");
assert(roadmap.includes("m37 shipped: terrain-aware sensor sampling on controlled cadence"), "roadmap must include m37 terrain sensor sampling.");
assert(roadmap.includes("m38 shipped: terrain-aware reproduction placement using offspring habitat acceptance"), "roadmap must include m38 terrain reproduction placement.");
assert(roadmap.includes("m39 low-resolution environmental flow field foundation"), "roadmap must include m39 flow field next candidate.");
