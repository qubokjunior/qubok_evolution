import { readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const readText = (relativePath) => readFileSync(resolve(projectRoot, relativePath), "utf8");
const assert = (condition, message) => { if (!condition) throw new Error(message); };
const packageJson = JSON.parse(readText("package.json"));
const appVersion = readText("src/shared/appVersion.ts");
const readme = readText("README.md");
const milestones = readText("docs/milestones.md");
const integrationM40 = readText("docs/integration_m40.md");
assert(packageJson.version === "0.1.0-milestone.40", "package.json must expose 0.1.0-milestone.40.");
assert(appVersion.includes("PROJECT_VERSION = \"0.1.0-milestone.40\""), "appVersion must expose milestone.40.");
assert(appVersion.includes("PROJECT_MILESTONE = 40"), "appVersion must expose milestone number 40.");
assert(appVersion.includes("PROJECT_MILESTONE_LABEL = \"m40\""), "appVersion must expose m40 label.");
assert(readme.includes("0.1.0-milestone.40"), "README.md must expose current milestone version.");
assert(readme.includes("Current status: m40"), "README.md must expose current status m40.");
for (const marker of ["| m32 |", "| m33 |", "| m34 |", "| m35 |", "| m36 |", "| m37 |", "| m38 |", "| m39 |", "| m40 |"]) assert(milestones.includes(marker), "docs/milestones.md missing marker: " + marker);
assert(integrationM40.includes("environmental field render snapshot"), "integration_m40 must describe environmental field render snapshot.");
assert(packageJson.scripts["test:field-render-snapshot"] === "node scripts/test-field-render-snapshot.mjs", "package.json must expose test:field-render-snapshot.");
assert(packageJson.scripts["test:repo-status"] === "node scripts/test-repo-status.mjs", "package.json must expose test:repo-status.");
assert(packageJson.scripts.test.includes("test:repo-status"), "npm run test must include test:repo-status.");
console.log("repo status tests passed");
