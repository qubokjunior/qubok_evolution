import { readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const readText = (relativePath) => readFileSync(resolve(projectRoot, relativePath), "utf8");
const assert = (condition, message) => { if (!condition) throw new Error(message); };
const packageJson = JSON.parse(readText("package.json"));
const appVersion = readText("src/shared/appVersion.ts");
const readme = readText("README.md");
const milestones = readText("docs/milestones.md");
const integrationM39 = readText("docs/integration_m39.md");
assert(packageJson.version === "0.1.0-milestone.39", "package.json must expose 0.1.0-milestone.39.");
assert(appVersion.includes("PROJECT_VERSION = \"0.1.0-milestone.39\""), "appVersion must expose milestone.39.");
assert(appVersion.includes("PROJECT_MILESTONE = 39"), "appVersion must expose milestone number 39.");
assert(appVersion.includes("PROJECT_MILESTONE_LABEL = \"m39\""), "appVersion must expose m39 label.");
assert(readme.includes("0.1.0-milestone.39"), "README.md must expose current milestone version.");
assert(readme.includes("Current status: m39"), "README.md must expose current status m39.");
for (const marker of ["| m32 |", "| m33 |", "| m34 |", "| m35 |", "| m36 |", "| m37 |", "| m38 |", "| m39 |"]) assert(milestones.includes(marker), "docs/milestones.md missing marker: " + marker);
assert(integrationM39.includes("environmental flow field"), "integration_m39 must describe environmental flow field.");
assert(packageJson.scripts["test:field"] === "node scripts/test-field.mjs", "package.json must expose test:field.");
assert(packageJson.scripts["test:repo-status"] === "node scripts/test-repo-status.mjs", "package.json must expose test:repo-status.");
assert(packageJson.scripts.test.includes("test:repo-status"), "npm run test must include test:repo-status.");
console.log("repo status tests passed");
