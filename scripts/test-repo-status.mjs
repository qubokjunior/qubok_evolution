import { readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const readText = (relativePath) => readFileSync(resolve(projectRoot, relativePath), "utf8");
const assert = (condition, message) => { if (!condition) throw new Error(message); };
const packageJson = JSON.parse(readText("package.json"));
const appVersion = readText("src/shared/appVersion.ts");
const readme = readText("README.md");
const milestones = readText("docs/milestones.md");
const integrationM38 = readText("docs/integration_m38.md");
assert(packageJson.version === "0.1.0-milestone.38", "package.json must expose 0.1.0-milestone.38.");
assert(appVersion.includes("PROJECT_VERSION = \"0.1.0-milestone.38\""), "appVersion must expose milestone.38.");
assert(appVersion.includes("PROJECT_MILESTONE = 38"), "appVersion must expose milestone number 38.");
assert(appVersion.includes("PROJECT_MILESTONE_LABEL = \"m38\""), "appVersion must expose m38 label.");
assert(readme.includes("0.1.0-milestone.38"), "README.md must expose current milestone version.");
assert(readme.includes("Current status: m38"), "README.md must expose current status m38.");
for (const marker of ["| m32 |", "| m33 |", "| m34 |", "| m35 |", "| m36 |", "| m37 |", "| m38 |"]) assert(milestones.includes(marker), "docs/milestones.md missing marker: " + marker);
assert(integrationM38.includes("terrain-aware reproduction placement"), "integration_m38 must describe terrain-aware reproduction placement.");
assert(packageJson.scripts["test:repo-status"] === "node scripts/test-repo-status.mjs", "package.json must expose test:repo-status.");
assert(packageJson.scripts.test.includes("test:repo-status"), "npm run test must include test:repo-status.");
console.log("repo status tests passed");
